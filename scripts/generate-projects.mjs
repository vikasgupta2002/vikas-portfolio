#!/usr/bin/env node
/**
 * Regenerate src/data/projects.ts from the compressed files in
 * public/videos/ (plus matching thumbs + previews).
 *
 * Usage:
 *   npm run generate-projects
 *
 * Requires ffprobe on PATH. For every public/videos/*.mp4 it reads
 * width / height / duration, derives orientation (9:16 vs 16:9) and
 * guesses a category: vertical under 60s -> "Reels", horizontal
 * under 60s -> "Ads", horizontal 60s+ -> "YouTube", anything else
 * keeps its previous category if the file already existed.
 * Titles come from the filename, cleaned up — edit them by hand
 * in src/data/projects.ts afterwards.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const VIDEOS_DIR = join(ROOT, "public/videos");
const OUT = join(ROOT, "src/data/projects.ts");

function probe(file) {
  const raw = execFileSync(
    "ffprobe",
    [
      "-v",
      "error",
      "-select_streams",
      "v:0",
      "-show_entries",
      "stream=width,height,duration",
      "-show_entries",
      "format=duration",
      "-of",
      "json",
      file,
    ],
    { encoding: "utf8" }
  );
  const data = JSON.parse(raw);
  const stream = data.streams?.[0] ?? {};
  const duration = parseFloat(stream.duration || data.format?.duration || "0");
  return { width: stream.width, height: stream.height, duration };
}

function cleanTitle(slug) {
  return slug
    .replace(/-/g, " ")
    .split(" ")
    .map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w))
    .join(" ");
}

function guessCategory(orientation, duration) {
  if (orientation === "vertical" && duration < 60) return "Reels";
  if (orientation === "horizontal" && duration < 60) return "Ads";
  if (orientation === "horizontal") return "YouTube";
  return "Reels";
}

// Keep hand-edited titles/categories when re-running.
let previous = {};
if (existsSync(OUT)) {
  const src = readFileSync(OUT, "utf8");
  for (const m of src.matchAll(/id:\s*"([^"]+)"[\s\S]*?title:\s*"([^"]+)"[\s\S]*?category:\s*"([^"]+)"/g)) {
    previous[m[1]] = { title: m[2], category: m[3] };
  }
}

const files = readdirSync(VIDEOS_DIR)
  .filter((f) => f.toLowerCase().endsWith(".mp4"))
  .sort();

const projects = files.map((file, i) => {
  const slug = file.replace(/\.mp4$/i, "");
  const { width, height, duration } = probe(join(VIDEOS_DIR, file));
  const orientation = height > width ? "vertical" : "horizontal";
  const prev = previous[slug];
  return {
    id: slug,
    title: prev?.title ?? cleanTitle(slug),
    category: prev?.category ?? guessCategory(orientation, duration),
    video: `/videos/${file}`,
    thumbnail: `/thumbs/${slug}.jpg`,
    preview: `/previews/${slug}.mp4`,
    orientation,
    duration: Math.round(duration * 10) / 10,
    width,
    height,
    _order: i,
  };
});

const header = `// ---------------------------------------------------------------------------
// AUTO-GENERATED by \`npm run generate-projects\` — see scripts/generate-projects.mjs
// It probes public/videos/*.mp4 with ffprobe for width / height / duration.
// Titles are cleaned-up filenames and categories are guesses — edit them
// by hand below (re-running the script keeps your edits for existing ids).
// To add a video: drop the compressed file + thumb + preview into public/
// (or run process-videos.sh), then run \`npm run generate-projects\`.
// To remove a video: delete its files from public/ and re-run the script.
//
// GUESSED TITLES / CATEGORIES — please correct these:
// Titles are "Demo 1" … "Demo 10" in file order, named at the owner's
// request. Rename them to real project names; the script keeps
// hand-edited titles for existing ids. Categories are all "Reels"
// (vertical + under 60s); re-categorise any that are actually
// YouTube / Ads / Motion Graphics.
// ---------------------------------------------------------------------------

export type Category =
  | "Reels"
  | "YouTube"
  | "Ads"
  | "Motion Graphics";

export type Project = {
  id: string;
  title: string;
  category: Category;
  video: string; // /videos/<slug>.mp4
  thumbnail: string; // /thumbs/<slug>.jpg
  preview: string; // /previews/<slug>.mp4 (4s muted hover clip)
  orientation: "vertical" | "horizontal";
  duration: number; // seconds
};
`;

const body = projects
  .map(
    (p) => `  {
    id: "${p.id}",
    title: "${p.title.replace(/"/g, '\\"')}",
    category: "${p.category}",
    video: "${p.video}",
    thumbnail: "${p.thumbnail}",
    preview: "${p.preview}",
    orientation: "${p.orientation}",
    duration: ${p.duration},
  },`
  )
  .join("\n");

writeFileSync(
  OUT,
  `${header}
export const projects: Project[] = [
${body}
];

export const categories: ("All" | Category)[] = [
  "All",
  "Reels",
  "YouTube",
  "Ads",
  "Motion Graphics",
];

// Hero background — the first project in the grid.
export const heroProject = projects[0];
`
);

console.log(`Wrote ${OUT} — ${projects.length} projects`);
for (const p of projects) {
  console.log(` - ${p.id}: "${p.title}" | ${p.category} | ${p.orientation} ${p.width}x${p.height} | ${p.duration}s`);
}
const totalBytes = files.reduce(
  (sum, f) => sum + statSync(join(VIDEOS_DIR, f)).size,
  0
);
console.log(`Total public/videos: ${(totalBytes / 1024 / 1024).toFixed(1)} MB`);
if (totalBytes > 100 * 1024 * 1024) {
  console.warn(
    "WARNING: public/videos is over 100 MB — Vercel's limits make this risky. " +
      "Host the videos on Cloudinary / Cloudflare R2 instead and point `video` at URLs (see README)."
  );
}
